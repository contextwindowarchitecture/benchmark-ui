const SELF_CHECK_WORDS: Record<string, string> = {
  grader: "Planted replies graded as intended",
  plant: "Plants made from the run's own probes",
  schema: "Scripts valid against their schema",
  determinism: "Scripts regenerated byte for byte",
  structure: "Scripts with the shared shape",
  replay: "Scripts whose text says their ground truth",
  fact: "Planted omissions the fact oracle reads right",
  baseline: "Baselines equal to hand-computed payloads",
  compliance: "Replies judged right against the IP rules",
}

/** S0's typed tallies: passed of total per check. */
export function SelfCheckPanel({ block }: { block: NonNullable<D2SuiteSummaryV1["self_check"]> }) {
  const entries = Object.entries(block).flatMap(([check, tally]) =>
    tally ? [{ check, ...tally }] : [],
  )
  return (
    <TableRegion label="Self-check table">
      <Table>
        <TableCaption className="sr-only">Each self-check, passed of total.</TableCaption>
        <TableHeader>
          <TableRow>
            <TableHead scope="col">Check</TableHead>
            <TableHead scope="col" className="text-right">
              Passed
            </TableHead>
            <TableHead scope="col">Status</TableHead>
          </TableRow>
        </TableHeader>
        <TableBody>
          {entries.map((entry) => (
            <TableRow key={entry.check} data-check={entry.check}>
              <TableCell>
                <div>{SELF_CHECK_WORDS[entry.check] ?? entry.check}</div>
                <div className="font-mono text-xs text-muted-foreground">{entry.check}</div>
              </TableCell>
              <TableCell className="tabular text-right">
                {formatCount(entry.passed)}
                <span className="font-light"> / {formatCount(entry.total)}</span>
              </TableCell>
              <TableCell>
                <StatusBadge
                  status={entry.total === 0 ? "na" : entry.passed === entry.total ? "pass" : "fail"}
                />
              </TableCell>
            </TableRow>
          ))}
        </TableBody>
      </Table>
    </TableRegion>
  )
}

/** S1's typed gate and row counts. */
export function GatePanel({ summary }: { summary: D2SuiteSummaryV1 }) {
  const gate = summary.gate
  const rows = summary.rows
  return (
    <div className="grid gap-4 md:grid-cols-2">
      {gate ? (
        <Card>
          <CardHeader>
            <CardTitle>Conversations and arms through the gate</CardTitle>
          </CardHeader>
          <CardContent className="space-y-2 text-sm">
            <p className="text-2xl font-semibold tabular">
              {formatCount(gate.passed)}
              <span className="text-base font-light text-muted-foreground">
                {" "}
                / {formatCount(gate.total)}
              </span>
            </p>
            <p className="text-muted-foreground">
              {gate.total > 0 ? formatPercent(gate.passed / gate.total) : "none gated"}. A pair
              passes only when every one of its rows does; S2 to S4 send only the pairs that pass.
            </p>
            {gate.failed.length > 0 ? (
              <ul className="font-mono text-xs">
                {gate.failed.map((pair) => (
                  <li key={pair}>{pair}</li>
                ))}
              </ul>
            ) : null}
          </CardContent>
        </Card>
      ) : null}
      {rows ? (
        <Card>
          <CardHeader>
            <CardTitle>Rows written</CardTitle>
          </CardHeader>
          <CardContent>
            <dl className="grid grid-cols-[auto_auto] justify-start gap-x-6 gap-y-1 text-sm">
              {(
                [
                  ["probes", "Probe snapshots"],
                  ["turns", "Turn frames"],
                  ["timelines", "Timelines"],
                  ["baselines", "Baseline payloads"],
                  ["lq", "Long-context snapshots"],
                  ["lq_baselines", "Long-context baselines"],
                ] as const
              ).map(([key, label]) =>
                rows[key] === undefined ? null : (
                  <div key={key} className="contents">
                    <dt className="text-muted-foreground">{label}</dt>
                    <dd className="tabular">{formatCount(rows[key] ?? 0)}</dd>
                  </div>
                ),
              )}
            </dl>
          </CardContent>
        </Card>
      ) : null}
    </div>
  )
}

/** S7's typed goldens block: what was compared with, and the drift found. */
export function GoldensPanel({ block }: { block: NonNullable<D2SuiteSummaryV1["goldens"]> }) {
  const drift = block.drift
  return (
    <Card>
      <CardHeader>
        <CardTitle>Golden drift</CardTitle>
      </CardHeader>
      <CardContent className="space-y-3 text-sm">
        <ul className="flex flex-wrap gap-3">
          {(["match", "spec_change", "regression", "new"] as const).map((kind) => (
            <li key={kind} className="flex items-center gap-2">
              <StatusBadge status={kind} />
              <span className="tabular">{formatCount(drift[kind])}</span>
            </li>
          ))}
          <li className="flex items-center gap-2">
            <span className="text-muted-foreground">removed</span>
            <span className="tabular">{formatCount(drift.removed)}</span>
          </li>
        </ul>
        <p className="text-muted-foreground">
          {block.path
            ? "Compared with the adopted goldens"
            : "No goldens were adopted when this run was made"}
          {block.contract_commit ? (
            <>
              {" "}
              of contract <span className="font-mono">{shortDigest(block.contract_commit)}</span>
            </>
          ) : null}
          .
        </p>
      </CardContent>
    </Card>
  )
}
