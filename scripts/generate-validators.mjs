#!/usr/bin/env node
// Generates standalone validators from the vendored schemas (ui-plan.md 5.3), so the viewer never
// compiles a schema in the browser: the deployed Content Security Policy is `script-src 'self'`
// with no 'unsafe-eval', and Ajv's compiler builds validators with `new Function`. Ajv's
// standalone code generation runs here, at build time, and the output is checked in beside the
// types under src/data/schema/generated/; `pnpm generate:types` regenerates both.
//
//   node scripts/generate-validators.mjs
//
// The standalone code references two runtime helpers through `require()`, which an ESM bundle
// cannot resolve: ajv-formats' format table (for `date-time` and `uri`) and Ajv's ucs2length (for
// minLength). The script rewrites those references to a top-level ESM import of the format table
// and a local copy of ucs2length, and fails if any other `require(` is left.

import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

import Ajv2020 from "ajv/dist/2020.js"
import standaloneCode from "ajv/dist/standalone/index.js"
import addFormats from "ajv-formats"
import { format } from "prettier"

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const schemasDir = join(root, "vendor/cwa-bench/domain1/schemas")
const outDir = join(root, "src/data/schema/generated")

const banner = (what) =>
  `// Generated by scripts/generate-validators.mjs from ${what}. Do not edit; re-run \`pnpm generate:types\`.\n`

const prettierStyle = { semi: false, singleQuote: false, printWidth: 100, trailingComma: "all" }

function pascal(kind) {
  return kind
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("")
}

function camel(name) {
  return name.charAt(0).toLowerCase() + name.slice(1)
}

// The same options as the viewer used at runtime before: every error is reported, strict mode,
// union types allowed (corpus-index declares one), formats from ajv-formats.
const ajv = new Ajv2020({
  code: { source: true, esm: true, optimize: 2 },
  allErrors: true,
  strict: true,
  allowUnionTypes: true,
})
addFormats(ajv)

const kinds = []
for (const file of readdirSync(schemasDir).sort()) {
  const match = /^([a-z0-9-]+)\.v([0-9]+)\.schema\.json$/.exec(file)
  if (!match) continue
  const [, kind, version] = match
  const schema = JSON.parse(readFileSync(join(schemasDir, file), "utf8"))
  ajv.addSchema(schema, schema.$id)
  kinds.push({
    kind,
    version: Number(version),
    typeName: `${pascal(kind)}V${version}`,
    id: schema.$id,
  })
}

const names = Object.fromEntries(kinds.map((k) => [camel(k.typeName), k.id]))
let code = standaloneCode(ajv, names)

// ucs2length, copied from ajv/dist/runtime/ucs2length.js (MIT, Evgeny Poberezkin): the length of
// a string in code points, as JSON Schema's minLength counts it.
const ucs2length = `function ucs2length(str) {
  const len = str.length
  let length = 0
  let pos = 0
  let value
  while (pos < len) {
    length++
    value = str.charCodeAt(pos++)
    if (value >= 0xd800 && value <= 0xdbff && pos < len) {
      value = str.charCodeAt(pos)
      if ((value & 0xfc00) === 0xdc00) pos++
    }
  }
  return length
}
`

const rewrites = [
  [/require\("ajv-formats\/dist\/formats"\)\.fullFormats/g, "fullFormats"],
  [/require\("ajv\/dist\/runtime\/ucs2length"\)\.default/g, "ucs2length"],
]
for (const [pattern, replacement] of rewrites) code = code.replace(pattern, replacement)
const leftover = code.match(/require\([^)]*\)/g)
if (leftover) {
  throw new Error(
    `standalone code still requires ${[...new Set(leftover)].join(", ")}; teach the script about it`,
  )
}
code = code.replace(/^"use strict";/, "")

mkdirSync(outDir, { recursive: true })
writeFileSync(
  join(outDir, "validators.js"),
  [
    banner("the vendored schemas"),
    "/* eslint-disable */",
    '"use strict"',
    'import { fullFormats } from "ajv-formats/dist/formats.js"',
    "",
    ucs2length,
    code,
    "",
  ].join("\n"),
)

const declarations = [
  banner("the vendored schemas"),
  'import type { ValidateFunction } from "ajv"',
  "",
  `import type { ${kinds.map((k) => k.typeName).join(", ")} } from "./index"`,
  "",
  ...kinds.map((k) => `export declare const ${camel(k.typeName)}: ValidateFunction<${k.typeName}>`),
  "",
].join("\n")
writeFileSync(
  join(outDir, "validators.d.ts"),
  await format(declarations, { ...prettierStyle, parser: "typescript" }),
)

const byKind = [
  banner("the vendored schemas"),
  'import type { ValidateFunction } from "ajv"',
  "",
  'import type { DocumentByKind, SchemaKind } from "./index"',
  'import * as standalone from "./validators"',
  "",
  "/** One standalone validator per kind, typed by the kind's document. */",
  "export const validators: { [K in SchemaKind]: ValidateFunction<DocumentByKind[K]> } = {",
  ...kinds.map((k) => `  "${k.kind}": standalone.${camel(k.typeName)},`),
  "}",
  "",
].join("\n")
writeFileSync(
  join(outDir, "validators-by-kind.ts"),
  await format(byKind, { ...prettierStyle, parser: "typescript" }),
)

process.stdout.write(
  `generated ${kinds.length} standalone validators into src/data/schema/generated/ (${code.length} bytes)\n`,
)
